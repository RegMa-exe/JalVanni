/**
 * Internal sort weight only (Incident.aiConfidence is numeric). Never display this
 * as a percentage — AI confidence is qualitative and uncalibrated.
 */
export const confidenceScore = { high: 0.9, medium: 0.7, low: 0.4 } as const

/** Qualitative label for any 0–1 confidence value (used for legacy demo records). */
export const qualitativeConfidence = (v: number): 'high' | 'medium' | 'low' => (v >= 0.85 ? 'high' : v >= 0.65 ? 'medium' : 'low')

/** Accepts records saved before Phase 3.1 (flat arrays) and the current grouped shape. */
export function normaliseActions(ra: unknown): { immediate_actions: string[]; after_verification_actions: string[] } {
  if (Array.isArray(ra)) return { immediate_actions: ra as string[], after_verification_actions: [] }
  const r = (ra ?? {}) as Partial<{ immediate_actions: string[]; after_verification_actions: string[] }>
  return { immediate_actions: r.immediate_actions ?? [], after_verification_actions: r.after_verification_actions ?? [] }
}

export function normaliseMissing(mi: unknown): { essential: string[]; optional_evidence: string[] } {
  if (Array.isArray(mi)) return { essential: mi as string[], optional_evidence: [] }
  const r = (mi ?? {}) as Partial<{ essential: string[]; optional_evidence: string[] }>
  return { essential: r.essential ?? [], optional_evidence: r.optional_evidence ?? [] }
}

/** "OpenRouter · qwen/qwen-2.5-72b-instruct" or "Rule-based fallback". */
export function analysisSourceLabel(rec: IncidentAnalysisRecord): string {
  return rec.source === 'ai' ? `${rec.meta.provider} · ${rec.meta.model}` : 'Rule-based fallback'
}
