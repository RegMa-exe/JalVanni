import type { AiIncidentAnalysis, AiIncidentType, AnalysisMeta, IncidentCategory, IncidentAnalysisRecord, SupplyImpact } from '@/types'
import { extractIncident } from '@/services/voice'

/**
 * Incident intelligence client.
 *
 * Primary: OpenRouter via the server-side proxy at /api/analyze (API key and
 * model id stay on the server). Fallback: the local rule-based extractor,
 * always labelled as such — never presented as an AI result.
 */

const CLIENT_TIMEOUT_MS = 75_000 // server budget is 60s incl. one retry

export interface AnalysisServiceStatus {
  provider: 'OpenRouter'
  model: string | null
  configured: boolean
  modelFound?: boolean | null
  modelName?: string | null
  structuredOutputs?: boolean | null
  suggestions?: string[]
}

export class AnalysisError extends Error {
  constructor(
    public code: string,
    message: string,
  ) {
    super(message)
  }
}

export async function getAnalysisStatus(): Promise<AnalysisServiceStatus> {
  const res = await fetch('/api/analyze/status')
  if (!res.ok) throw new AnalysisError('STATUS_UNAVAILABLE', 'Analysis service is unreachable.')
  return res.json()
}

export async function analyzeWithAi(
  transcript: string,
  detectedLanguageCode: string | null,
  signal?: AbortSignal,
): Promise<{ result: AiIncidentAnalysis; meta: AnalysisMeta }> {
  const timeout = AbortSignal.timeout(CLIENT_TIMEOUT_MS)
  const combined = signal ? AbortSignal.any([signal, timeout]) : timeout
  let res: Response
  try {
    res = await fetch('/api/analyze', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ transcript, detectedLanguageCode }),
      signal: combined,
    })
  } catch (e) {
    if (signal?.aborted) throw new AnalysisError('CANCELLED', 'Analysis was cancelled.')
    if (timeout.aborted) throw new AnalysisError('TIMEOUT', `No response within ${CLIENT_TIMEOUT_MS / 1000}s.`)
    throw new AnalysisError('NETWORK_ERROR', `Could not reach the JalVaani server (${(e as Error).message}).`)
  }
  const body = await res.json().catch(() => null)
  if (!res.ok || !body?.analysis) {
    throw new AnalysisError(body?.error?.code ?? `HTTP_${res.status}`, body?.error?.message ?? 'Analysis failed.')
  }
  return { result: body.analysis, meta: body.meta }
}

// ---- Rule-based fallback -----------------------------------------------------

const categoryToType: Partial<Record<IncidentCategory, AiIncidentType>> = {
  'Pipe Burst': 'pipe_burst',
  Leakage: 'pipeline_leak',
  'No Supply': 'water_shortage',
  'Low Pressure': 'low_pressure',
  Contamination: 'suspected_contamination',
}

/** Runs the local keyword extractor and shapes it like an AI result, clearly marked as fallback. */
export function ruleBasedFallback(transcript: string, reason: string): IncidentAnalysisRecord {
  const x = extractIncident(transcript)
  const supply: SupplyImpact = x.entities.find((e) => e.label === 'Supply impact')?.value === 'Yes' ? 'no_supply' : 'unknown'
  const location = x.location === 'Location to be confirmed' ? null : x.location
  return {
    source: 'rule_based_fallback',
    fallbackReason: reason,
    analysedAt: new Date().toISOString(),
    result: {
      incident_type: categoryToType[x.category] ?? 'other',
      location,
      landmark: null,
      severity: x.severity,
      description: `Keyword match only. ${x.summary}`,
      water_supply_impact: supply,
      affected_population: { scope: null, estimated_households: null },
      severity_rationale: 'Keyword-based default for this category — not evidence-assessed. Operator must set severity after verification.',
      recommended_action: {
        immediate_actions: ['Operator to review the transcript and classify manually', 'Call back the caller to confirm location and details'],
        after_verification_actions: ['If verified, raise a work order for the appropriate crew'],
      },
      missing_information: {
        essential: ['All fields need manual verification (rule-based fallback)', ...(location ? [] : ['Exact location'])],
        optional_evidence: [],
      },
      requires_human_review: true,
      reasoning: 'Generated by the local keyword extractor because AI analysis was unavailable. It does not understand context.',
      verification_status: 'reported_unverified',
      confidence: 'low',
    },
  }
}

