/** Hourly incident intake over the last 24h. */
export const hourlyIntake = Array.from({ length: 24 }, (_, i) => {
  const hour = (new Date().getHours() - 23 + i + 24) % 24
  const base = 4 + Math.round(6 * Math.sin(((hour - 5) / 24) * Math.PI * 2) ** 2)
  const voice = base + ((i * 7) % 5)
  const other = Math.max(1, Math.round(base / 2) + ((i * 3) % 3))
  return { hour: `${String(hour).padStart(2, '0')}:00`, voice, other }
})

